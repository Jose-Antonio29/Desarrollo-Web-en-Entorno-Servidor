<?php
    // Declaro 2 cadenas de texto
    $cadena1 = "Hola";
    $cadena2 = "Mundo";

    // Declaro 2 enteros
    $numeroEntero1 = 12;
    $numeroEntero2 = 5;

    // Declaro 2 decimales
    $numeroDecimal1 = 7.32;
    $numeroDecimal2 = 2.35;

    // Muestro cadena1 por pantalla
    echo ($cadena1);
    echo ("<br>");

    // Muestro por pantalla la concatenación de las dos cadenas
    echo ($cadena1 . $cadena2);
    echo ("<br>");

    // Sumo los dos enteros y muestro el resultado por pantalla
    echo($numeroEntero1 + $numeroEntero2);
    echo ("<br>");

    // Resto el decimal 1 al decimal 2 y muestro el resultado por pantalla
    echo($numeroDecimal2 - $numeroEntero1);
    echo ("<br>");

    // Multiplico el decimal 1 por el decimal 2 y muestro el resultado por pantalla
    echo($numeroDecimal1 * $numeroEntero2);
    echo("<br>");
?>